# 1. Створюємо список заявок
tickets = ["Low", "High", "Medium", "High", "Low"]

print("Розпочинаємо перевірку пріоритетних заявок...")

# 2. Проходимо циклом по списку
for level in tickets:
    
    # ТУТ МАЄ БУТИ ТВОЯ УМОВА 'if'
    # Підказка: перевір, чи дорівнює level значенню "High"
    if level == "High":
        print("Знайдено термінову заявку! Потрібна негайна дія.")
    else:
        print("Звичайна заявка. Можна опрацювати пізніше.")

print("Перевірку завершено.")